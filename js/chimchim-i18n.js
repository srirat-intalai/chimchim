// เก็บค่าที่ผู้ใช้เลือกไว้ใน localStorage คีย์เดียว: chimchim_prefs

var CHIMCHIM_PREFS_KEY = "chimchim_prefs";

function getPrefs() {
	try {
		return JSON.parse(localStorage.getItem(CHIMCHIM_PREFS_KEY)) || {};
	} catch (e) {
		return {};
	}
}
function savePrefs(patch) {
	var p = getPrefs();
	var key;
	for (key in patch) {
		if (Object.prototype.hasOwnProperty.call(patch, key)) p[key] = patch[key];
	}
	localStorage.setItem(CHIMCHIM_PREFS_KEY, JSON.stringify(p));
}
// ภาษาเริ่มต้นของแอปคือไทย ผู้ใช้เปลี่ยนเป็นอังกฤษได้ในหน้า Settings
function getLang() {
	return getPrefs().lang === "en" ? "en" : "th";
}
function setLang(lang) {
	savePrefs({ lang: lang === "th" ? "th" : "en" });
	applyI18n();
}
// ธีมมีแค่ 2 แบบ: "light" (ค่าเริ่มต้น) / "dark" — ตัวเลือก "ตามระบบ" ถูกเอาออกแล้ว
// คนที่เคยเลือก "system" ไว้: แปลงเป็นธีมที่เครื่องใช้อยู่ตอนนี้ครั้งเดียวแล้วบันทึกเลย (หน้าตาไม่กระโดดเปลี่ยน)
(function migrateSystemTheme() {
	if (getPrefs().theme !== "system") return;
	var osDark = !!(window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches);
	savePrefs({ theme: osDark ? "dark" : "light" });
})();
function getThemeChoice() {
	return getPrefs().theme === "dark" ? "dark" : "light";
}
function getTheme() {
	return getThemeChoice();
}
function setTheme(theme) {
	savePrefs({ theme: theme === "dark" ? "dark" : "light" });
	applyThemeAttr();
}
function applyThemeAttr() {
	document.documentElement.setAttribute("data-theme", getTheme());
	// สีแถบสถานะเบราว์เซอร์มือถือให้ตามธีมด้วย ไม่งั้นโหมดมืดยังมีแถบม่วงสว่างค้างอยู่ด้านบน
	var meta = document.querySelector('meta[name="theme-color"]');
	var journal = document.body && document.body.classList.contains("journal");
	if (meta) meta.setAttribute("content", getTheme() === "dark" ? "#15131b" : (journal ? "#FAF9F6" : "#6842b5"));
}
applyThemeAttr();
document.documentElement.setAttribute("lang", getLang());

